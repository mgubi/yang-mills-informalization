#!/usr/bin/env bash
# Publish the built site (tm/html/) to the gh-pages branch of the Pages repository.
#
#   tm/publish.sh            commit tm/html/ as it is and push it
#   tm/publish.sh --dry-run  prepare the commit in a temporary clone, do not push
#
# The site is built by tm/build.sh, locally or by the CI workflow; this script
# only copies the finished HTML. History of gh-pages is kept: each publish is
# one commit recording the source commit it was built from (also written to
# .source-commit, which the CI workflow reads).
#
# Environment:
#   YM_PAGES_REMOTE  push URL (default git@github.com:mgubi/yang-mills-informalization.git)
#   YM_PAGES_BRANCH  branch (default gh-pages)
set -eo pipefail

here=$(cd "$(dirname "$0")" && pwd -P)
repo=$(dirname "$here")
html=$here/html
remote=${YM_PAGES_REMOTE:-git@github.com:mgubi/yang-mills-informalization.git}
branch=${YM_PAGES_BRANCH:-gh-pages}
dry=0
[[ ${1:-} == --dry-run ]] && dry=1

[[ -f $html/index.html ]] || { echo "no site in $html: run tm/build.sh first" >&2; exit 1; }

src=$(git -C "$repo" rev-parse HEAD)
srcbranch=$(git -C "$repo" rev-parse --abbrev-ref HEAD)
dirty=""
[[ -n $(git -C "$repo" status --porcelain -- . ':!tm') ]] && dirty=" (with uncommitted changes)"

work=$(mktemp -d "${TMPDIR:-/tmp}/ym-pages.XXXXXX")
trap 'rm -rf "$work"' EXIT

if git ls-remote --exit-code --heads "$remote" "$branch" >/dev/null 2>&1; then
  git clone --quiet --depth 1 --branch "$branch" "$remote" "$work/site"
else
  git init --quiet "$work/site"
  git -C "$work/site" checkout --quiet --orphan "$branch"
  git -C "$work/site" remote add origin "$remote"
fi

# replace the whole tree with the current build
find "$work/site" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
rsync -a "$html/" "$work/site/"
touch "$work/site/.nojekyll"   # serve files as they are, no Jekyll processing
printf '%s\n' "$src" > "$work/site/.source-commit"   # read by the CI workflow

cd "$work/site"
git add -A
if git diff --cached --quiet; then
  echo "gh-pages already up to date"
  exit 0
fi
git commit --quiet -m "Site built from ${src:0:7}${dirty}

Generated by tm/build.sh and published by tm/publish.sh from
commit $src ($srcbranch)

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"
git --no-pager log --oneline -1

if (( dry )); then
  echo "dry run: not pushed (clone in $work/site is deleted on exit)"
else
  git push --quiet origin "$branch"
  echo "pushed to $remote ($branch)"
fi
